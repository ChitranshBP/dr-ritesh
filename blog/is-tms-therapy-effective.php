</ul>

<h2 id="tms-vs-antidepressants">How Does TMS Compare to Antidepressants?</h2>
<p>
    <strong>For people who have already tried medication without success, TMS often outperforms switching to another antidepressant.</strong> The landmark STAR*D study showed that the chance of remission drops sharply with each new medication attempt, falling to roughly 13–14% by the third or fourth try. You can read more about the <a href="https://en.wikipedia.org/wiki/STAR*D" target="_blank" rel="noopener">STAR*D trial on Wikipedia</a>.
</p>
<p>
    By comparison, real-world TMS remission rates of around 30–40% in similar patients are notably higher.
</p>

