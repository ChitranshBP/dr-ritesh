<h2 id="is-tms-safe">Is TMS Safe as Well as Effective?</h2>
<p>
    <strong>Yes. TMS has a strong safety record.</strong> The most common side effects are mild scalp discomfort and headaches during the first week, which usually fade as treatment continues. The risk of seizure is very rare, estimated at less than 1 in 30,000 treatments.
</p>
<p>
    Unlike electroconvulsive therapy (ECT), TMS does not require anesthesia and <a href="/blog/does-tms-cause-memory-loss">does not cause memory loss</a>. For full details, see our article <a href="/blog/is-tms-therapy-safe">Is TMS Therapy Safe?</a> and our explanation of <a href="/blog/is-tms-legitimate">whether TMS is legitimate</a>.
</p>

