<h2 id="what-is-tms-therapy">What Is TMS Therapy and How Does It Work?</h2>
<p>
    <strong>TMS therapy uses focused magnetic pulses to stimulate the parts of the brain that control mood.</strong> A treatment coil is placed gently against the scalp, and it sends pulses to the <strong>left dorsolateral prefrontal cortex</strong>, a region that brain scans show is underactive in people with depression.
</p>
<p>
    These pulses produce small electrical currents in the nerve cells beneath the coil. Over repeated sessions, this strengthens the communication between brain regions involved in mood, motivation, and emotional control. Scientists call this process <strong>neuroplasticity</strong>, the brain's ability to rewire itself.
</p>
<p>
    You stay awake during treatment, you can drive yourself home, and you can return to work the same day. For a deeper technical background, see <a href="https://en.wikipedia.org/wiki/Transcranial_magnetic_stimulation" target="_blank" rel="noopener">Wikipedia's overview of Transcranial Magnetic Stimulation</a>.
</p>

<h2 id="what-the-research-says">What Does the Research Say About TMS Effectiveness?</h2>
<p>
    TMS has been studied for more than 30 years in thousands of patients. Here is what the most important research shows.
</p>

<h3 id="controlled-trials">Randomized Controlled Trials</h3>
<p>
    The trials that led to FDA clearance in 2008 compared real TMS to a "sham" (fake) treatment. Patients receiving real TMS improved significantly more than those receiving sham stimulation. A large trial funded by the National Institute of Mental Health (NIMH) confirmed these results independently, showing that patients receiving active TMS were about <strong>four times more likely to reach remission</strong> than those in the sham group.
</p>

<h3 id="real-world-studies">Real-World Clinical Studies</h3>
<p>
    Controlled trials use strict rules. Real-world studies show how TMS performs in everyday clinics. A widely cited multi-site study of more than 300 patients across 42 U.S. practices found:
</p>
<ul>
    <li><strong>58% of patients responded</strong> (at least a 50% reduction in symptoms)</li>
    <li><strong>37% reached remission</strong> (symptoms reduced to a minimal level)</li>
    <li>Results held up even in patients who had failed several medications</li>
</ul>
<p>
    You can review how these numbers break down by condition on our <a href="/tms-therapy-success-rate">TMS therapy success rate</a> page.
</p>

<h3 id="long-term-results">Long-Term Results</h3>
<p>
    One of the most common questions is <em>how long does TMS last?</em> In a one-year follow-up of the same real-world group, about <strong>two-thirds of patients who responded still met response criteria 12 months later</strong>. Some patients benefit from occasional "booster" sessions to maintain results.
</p>

<h3 id="newer-protocols">Newer, Faster Protocols</h3>
<p>
    Research continues to improve TMS. A major 2018 trial published in <em>The Lancet</em> found that <strong>theta burst stimulation</strong>, which takes about 3 minutes per session, works as well as the standard 19- to 37-minute protocol. Newer <a href="/accelerated-tms-therapy-nj">accelerated TMS protocols</a> deliver several sessions per day and have shown promising early results in smaller studies.
</p>

