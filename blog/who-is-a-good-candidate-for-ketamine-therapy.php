<h2 id="who-should-not-receive">Who Should NOT Receive Ketamine Therapy? (Contraindications)</h2>
<p>
    While ketamine has an established safety profile in medical environments, it is not appropriate for every patient. During your clinical screening with Dr. Ritesh Amin, we evaluate for key contraindications:
</p>
<ul>
    <li><strong>Uncontrolled Stage II Hypertension or Aneurysm:</strong> Ketamine temporarily increases blood pressure and heart rate during administration. Patients with resting blood pressure exceeding 160/100 mmHg, unstable angina, recent heart attack, or vascular aneurysms must obtain medical clearance before treatment.</li>
    <li><strong>Active Psychotic Disorders:</strong> Because ketamine is a dissociative compound, it can worsen thought disorganization, delusions, or hallucinations in individuals with schizophrenia, schizoaffective disorder, or active psychosis.</li>
    <li><strong>Active Mania:</strong> Patients experiencing an active manic or hypomanic episode should not undergo ketamine infusions until their mood is stabilized.</li>
    <li><strong>Active Substance Use Disorders:</strong> Candidates must be able to engage reliably with scheduled appointments. Active, untreated abuse of alcohol, cocaine, or illicit dissociative drugs requires stabilization before starting ketamine.</li>
    <li><strong>Severe Liver Disease:</strong> Ketamine is cleared by hepatic enzymes. Patients with end-stage liver disease or acute hepatic failure may experience altered drug clearance.</li>
    <li><strong>Pregnancy and Breastfeeding:</strong> Ketamine safety during pregnancy has not been established; therefore, pregnant or nursing women are not eligible for treatment.</li>
</ul>

