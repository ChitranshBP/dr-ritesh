<h2 id="common-temporary-side-effects">Common and Temporary Side Effects of TMS Therapy</h2>
<p>
    While memory loss is not a side effect of TMS, patients should understand the genuine, temporary physiological responses that may occur:
</p>
<p>
    Because TMS is non-systemic (it does not enter the bloodstream), it avoids the side effects of antidepressant pills—such as sexual dysfunction, weight gain, nausea, and emotional numbness. Read our full analysis of <a href="/tms-therapy-side-effects-safety.php">TMS side effects and safety profile</a>.
</p>
<p>
    The documented side effects of TMS are mild, localized, and short-lived:
</p>
<ul>
    <li><strong>Scalp Discomfort:</strong> Patients feel a localized tapping on the scalp beneath the coil. This sensation diminishes as the scalp desensitizes during the first 5 to 7 sessions.</li>
    <li><strong>Mild Tension Headache:</strong> Roughly one-third of patients experience a mild headache after early sessions from superficial muscle activation. These respond quickly to over-the-counter pain relievers and resolve after week one.</li>
    <li><strong>Facial Muscle Twitching:</strong> If pulses fringe facial nerves, slight temporary twitching of the eye or jaw may occur during pulses. Clinicians eliminate this by adjusting coil position.</li>
    <li><strong>Transient Lightheadedness:</strong> A small fraction of patients feel brief dizziness when standing after a session, resolving in minutes.</li>
    <li><strong>Seizure Risk (Extremely Rare):</strong> The seizure risk with TMS is under <strong>0.01% per session</strong> (less than 1 in 10,000)—lower than many antidepressant medications. Pre-screening ensures high safety.</li>
</ul>

