    <li><strong>Synaptic Neuroplasticity:</strong> Magnetic pulses trigger Long-Term Potentiation (LTP), strengthening synaptic connections and stimulating <em>Brain-Derived Neurotrophic Factor (BDNF)</em> release to repair neural branching.</li>
    <li><strong>Enhanced Connectivity:</strong> By re-establishing healthy communication between the prefrontal cortex and striatum, TMS normalizes processing speed and working memory capacity.</li>
</ul>
