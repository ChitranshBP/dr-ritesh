<h2 id="why-patients-worry-tms-vs-ect">Why Patients Worry About Memory Loss: TMS vs. ECT</h2>
<p>
    The most common reason prospective patients ask whether TMS therapy causes memory loss stems from confusion between <strong>Transcranial Magnetic Stimulation (TMS)</strong> and <strong>Electroconvulsive Therapy (ECT)</strong>. Although both are brain stimulation treatments, their mechanisms, protocols, and safety profiles are fundamentally different:
</p>

<ul>
    <li><strong>Electroconvulsive Therapy (ECT):</strong> ECT delivers electrical currents across electrodes on the scalp under general anesthesia and muscle relaxation. This current intentionally induces a brief generalized seizure. A well-known side effect is retrograde amnesia (loss of past memories) and temporary anterograde amnesia. Learn more in our comparison of <a href="/tms-therapy-vs-ect.php">TMS therapy vs. ECT</a>.</li>
    <li><strong>Transcranial Magnetic Stimulation (TMS):</strong> TMS utilizes focused magnetic pulses—identical in physics to an MRI scan. TMS delivers pulses to precise millimeter targets on the cerebral cortex without passing electricity through the skull, without general anesthesia, and without triggering seizures. Patients remain awake and comfortable, able to converse or listen to music during each 19-to-37-minute session.</li>
</ul>

<p>
    Because TMS is targeted solely to specific mood-regulating regions rather than diffusing across the brain, memory centers like the hippocampus are never exposed to electrical trauma. Authoritative medical resources like <a href="https://en.wikipedia.org/wiki/Transcranial_magnetic_stimulation" target="_blank" rel="noopener">Wikipedia's Transcranial Magnetic Stimulation overview</a> and <a href="https://en.wikipedia.org/wiki/Electroconvulsive_therapy" target="_blank" rel="noopener">Electroconvulsive Therapy documentation</a> emphasize that the absence of memory disruption is why TMS was developed and granted FDA clearance.
</p>

