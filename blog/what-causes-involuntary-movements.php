<h2 id="primary-causes">Primary Causes of Involuntary Movements</h2>
<p>
    Involuntary movements stem from a wide spectrum of neurological, pharmacological, structural, and metabolic factors. The primary causes include:
</p>

<h3 id="cause-neurodegenerative">1. Neurodegenerative Disorders</h3>
<p>
    Chronic progressive neurodegenerative conditions directly impair basal ganglia pathways and motor cortical connectivity:
</p>
<ul>
    <li><strong>Parkinson's Disease:</strong> Degeneration of dopaminergic neurons in the <em>substantia nigra pars compacta</em> disrupts basal ganglia signaling, causing resting tremors, muscle rigidity, bradykinesia, and gait freezing.</li>
    <li><strong>Huntington's Disease:</strong> An inherited autosomal dominant mutation leads to progressive atrophy of the caudate nucleus and putamen, resulting in severe chorea, cognitive decline, and psychiatric changes.</li>
    <li><strong>Multiple Sclerosis (MS):</strong> Inflammatory demyelination along motor control pathways in the brainstem and cerebellum causes intention tremors, painful spasticity, and involuntary muscle spasms.</li>
</ul>

<h3 id="cause-medications">2. Medication Side Effects &amp; Tardive Dyskinesia</h3>
<p>
    Prolonged blockade of central dopamine D2 receptors by psychiatric or gastrointestinal medications induces compensatory D2 receptor hypersensitivity and neurostructural modifications in the striatum. Over time, this leads to <strong>tardive dyskinesia</strong>, tardive dystonia, or drug-induced parkinsonism.
</p>
<p>
    Culprit medications include:
</p>
<ul>
    <li>First-generation antipsychotics (haloperidol, fluphenazine, chlorpromazine).</li>
    <li>Second-generation atypical antipsychotics (risperidone, olanzapine, quetiapine, aripiprazole).</li>
    <li>Anti-nausea and motility drugs (metoclopramide, prochlorperazine).</li>
    <li>Certain anticonvulsants, mood stabilizers, and high-dose central nervous system stimulants.</li>
</ul>

<h3 id="cause-brain-injury">3. Traumatic Brain Injury (TBI) &amp; Stroke</h3>
<p>
    Focal lesions caused by ischemic or hemorrhagic strokes in the thalamus, basal ganglia, or motor cortex can permanently disrupt inhibitory motor networks. Post-stroke movement disorders can manifest weeks or months after the initial event as focal dystonia, action tremors, or hemiballismus. Similarly, traumatic brain injuries can damage cerebellar peduncles, leading to persistent intention tremors.
</p>

<h3 id="cause-metabolic">4. Metabolic, Electrolyte &amp; Toxic Imbalances</h3>
<p>
    Systemic physiological perturbations directly alter neuronal membrane potentials and neurotransmitter synthesis:
</p>
<ul>
    <li>Severe deficiencies in magnesium, calcium, or potassium trigger widespread muscular hyperexcitability and fasciculations.</li>
    <li>Thyroid disorders (especially severe hyperthyroidism) cause fine postural tremors and muscle weakness.</li>
    <li>Hepatic encephalopathy produces <em>asterixis</em>—a coarse, flapping tremor of the wrists caused by toxic ammonia accumulation.</li>
    <li>Vitamin B12 deficiency, chronic alcoholism, and heavy metal toxicities (such as copper accumulation in Wilson's disease).</li>
</ul>

<h3 id="cause-fnd">5. Functional Neurological Disorder (FND) &amp; Stress</h3>
<p>
    Functional movement disorders (formerly termed psychogenic movement disorders) occur when the brain's functional software—how neural networks send and process signals—malfunctions without structural tissue damage. Severe emotional stress, physical trauma, or panic can trigger hyperactive limbic-motor interactions, manifesting as severe functional tremors, gait abnormalities, or myoclonic jerks.
</p>

