<h2 id="what-is-ptsd">What Is PTSD and Why Can It Be Disabling?</h2>
<p>
    <strong>Post-traumatic stress disorder (PTSD) is a mental health condition that can develop after experiencing or witnessing a traumatic event.</strong> Common causes include combat, assault, serious accidents, natural disasters, abuse, and work-related trauma among first responders and healthcare workers. For a clinical overview, see <a href="https://en.wikipedia.org/wiki/Post-traumatic_stress_disorder" target="_blank" rel="noopener">Wikipedia's article on post-traumatic stress disorder</a>.
</p>
<p>
    PTSD symptoms fall into four main groups:
</p>
<ul>
    <li><strong>Intrusive memories:</strong> Flashbacks, nightmares, and distressing thoughts about the trauma.</li>
    <li><strong>Avoidance:</strong> Staying away from people, places, or situations that bring back memories.</li>
    <li><strong>Negative changes in mood and thinking:</strong> Guilt, hopelessness, emotional numbness, and memory problems.</li>
    <li><strong>Hyperarousal:</strong> Irritability, poor sleep, trouble concentrating, and being easily startled.</li>
</ul>
<p>
    When these symptoms are severe, they can make it very difficult to hold a job. People may struggle to concentrate, miss work because of panic or poor sleep, or find it impossible to be around coworkers and customers. That loss of work capacity is what disability programs measure.
</p>

<h2 id="ssa-disability-ptsd">How Social Security Evaluates PTSD for Disability</h2>
<p>
    <strong>The SSA approves PTSD claims in two ways: by meeting the Listing 12.15 criteria, or by showing your symptoms leave you unable to do any full-time work.</strong> Social Security offers two programs:
</p>
<ul>
    <li><strong>SSDI (Social Security Disability Insurance):</strong> For people who have worked and paid Social Security taxes long enough.</li>
    <li><strong>SSI (Supplemental Security Income):</strong> A needs-based program for people with limited income and resources.</li>
</ul>

<h3 id="listing-12-15-criteria">Meeting SSA Listing 12.15</h3>
<p>
    To meet the listing, your medical records must document exposure to a traumatic event along with ongoing symptoms such as intrusive memories, avoidance, mood changes, and heightened arousal. You must then show <strong>one</strong> of the following:
</p>
<ul>
    <li><strong>Paragraph B:</strong> An extreme limitation in one, or a marked limitation in two, of these areas: understanding and remembering information; interacting with others; concentrating and keeping pace; and adapting or managing yourself.</li>
    <li><strong>Paragraph C:</strong> A "serious and persistent" condition documented for at least two years, with ongoing treatment that reduces symptoms, but only a minimal ability to adapt to changes in daily demands.</li>
</ul>
<p>
    You can review the official criteria in the <a href="https://www.ssa.gov/disability/professionals/bluebook/12.00-MentalDisorders-Adult.htm" target="_blank" rel="noopener">SSA Blue Book section on adult mental disorders</a>.
</p>

<h3 id="residual-functional-capacity">If You Do Not Meet the Listing</h3>
<p>
    Many people are approved even without meeting the listing exactly. The SSA assesses your <strong>residual functional capacity (RFC)</strong>, which describes the most you can still do despite your symptoms. If your PTSD prevents you from staying on task, following instructions, working around others, or showing up reliably, the SSA may find that no suitable jobs exist for you.
</p>

<h2 id="va-disability-ptsd">VA Disability Benefits for PTSD (Veterans)</h2>
<p>
    <strong>Veterans can receive VA disability compensation for PTSD connected to their military service.</strong> To qualify, a veteran generally needs a current PTSD diagnosis, evidence of an in-service stressor, and a medical link between the two.
</p>
<p>
    The VA assigns a rating of <strong>0%, 10%, 30%, 50%, 70%, or 100%</strong> based on how much PTSD affects work and social functioning. Higher ratings reflect more severe symptoms, such as frequent panic attacks, difficulty maintaining relationships, or an inability to work. Veterans can receive VA benefits and SSDI at the same time, since the two programs use separate rules.
</p>

