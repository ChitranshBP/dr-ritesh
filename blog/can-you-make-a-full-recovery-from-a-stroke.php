<h3 id="how-tms-works-stroke"><span class="step-num">1.</span> How TMS Restores Neural Network Signaling</h3>
<p>
    During a stroke rehabilitation TMS protocol, a specialized magnetic coil is placed against the scalp over target cortical regions—such as the primary motor cortex (M1) or supplementary motor area (SMA). Depending on the clinical goal, TMS can be applied in two primary stimulation modes:
</p>
<ul>
    <li>
        <strong>High-Frequency (Excitatory) TMS:</strong> Applied to the damaged brain hemisphere to stimulate sluggish neurons, promote synaptic sprouting, and enhance local cortical excitability.
    </li>
    <li>
        <strong>Low-Frequency (Inhibitory) TMS:</strong> Applied to the healthy, non-lesioned hemisphere to reduce pathologically high interhemispheric inhibition, freeing the injured hemisphere to execute motor learning.
    </li>
</ul>

