                tocLinks.forEach(function (l) { l.classList.toggle('active', l.getAttribute('href') === '#' + id); });
                drawerLinks.forEach(function (l) { l.classList.toggle('active', l.getAttribute('href') === '#' + id); });
            }
        });
    }, { rootMargin: '-10% 0px -75% 0px', threshold: 0 });
