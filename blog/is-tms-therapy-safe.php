<h2 id="side-effects">Common vs. Rare Side Effects of TMS Therapy</h2>
<p>
    One of the primary advantages of TMS therapy is its mild side-effect profile. Because TMS operates locally rather than systemically, side effects are overwhelmingly mild, localized to the head or scalp, and temporary.
