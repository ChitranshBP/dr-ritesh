<h3 id="strict-contraindications">Strict Contraindications (Ineligible for TMS)</h3>
<p>
    TMS uses strong magnetic fields, which means individuals with ferromagnetic metals or magnetic sensitive devices implanted in or near the head (within 30 cm of the TMS coil) cannot receive treatment:
</p>
<ul>
    <li>Aneurysm clips or coils in the brain</li>
    <li>Stents in the neck or brain blood vessels</li>
    <li>Deep brain stimulators (DBS)</li>
    <li>Cochlear implants or metallic ear implants</li>
    <li>Ocular metallic implants or shrapnel near the head</li>
</ul>
<p>
    <em>Note: Standard dental fillings, crowns, braces, and non-magnetic facial implants do NOT interfere with TMS safety and are completely allowed.</em>
</p>

<h3 id="relative-contraindications">Precautions Evaluated on a Case-by-Case Basis</h3>
<ul>
    <li>History of unmanaged seizure disorders or epilepsy</li>
    <li>Presence of cardiac pacemakers or vagus nerve stimulators (VNS) located in the chest</li>
    <li>Severe active substance abuse or acute withdrawal states that lower seizure thresholds</li>
</ul>
