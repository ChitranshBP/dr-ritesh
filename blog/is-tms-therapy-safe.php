<h3 id="common-side-effects">1. Common, Temporary Side Effects</h3>
<p>
    The vast majority of side effects occur only during or immediately following treatment sessions and diminish significantly as the scalp adapts over the first 1 to 2 weeks of care:
</p>
<ul>
    <li><strong>Scalp Discomfort or Tenderness:</strong> Feeling a light tapping or tingling sensation against the scalp while the magnetic coil pulses.</li>
    <li><strong>Mild Tension Headaches:</strong> Mild headaches after sessions, which are easily managed with over-the-counter pain relievers like acetaminophen or ibuprofen.</li>
    <li><strong>Facial Muscle Twitching:</strong> Minor, transient twitching in the forehead or eye area during active pulse delivery, which stops immediately when pulses cease.</li>
    <li><strong>Lightheadedness:</strong> Occasional mild dizziness immediately after standing up from the treatment chair, resolving within a few minutes.</li>
</ul>

<h3 id="rare-side-effects">2. Rare Side Effects & Seizure Risk</h3>
<p>
