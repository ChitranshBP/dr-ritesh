<script>
    // ── Pagination Configuration ──
    const POSTS_PER_PAGE = 9; // Exactly 9 blogs on page 1 (3x3 grid)
    const MIN_PAGES = 3;      // Ensures page 1, 2, 3 buttons are rendered as requested
    let currentPage = 1;

    // Read ?page= from URL on load
    const urlParams = new URLSearchParams(window.location.search);
    const initialPage = parseInt(urlParams.get('page'), 10);
    if (!isNaN(initialPage) && initialPage >= 1) {
        currentPage = initialPage;
    }

    const allCards = Array.from(document.querySelectorAll('#blog-grid > article.blog-card'));
    const emptyPageState = document.getElementById('blog-page-empty');
    const paginationNumbers = document.getElementById('pagination-numbers');
    const prevBtn = document.getElementById('pagination-prev');
    const nextBtn = document.getElementById('pagination-next');
    const paginationSummary = document.getElementById('pagination-summary');

    function renderPagination() {
        const totalCards = allCards.length;
        const totalPages = Math.max(MIN_PAGES, Math.ceil(totalCards / POSTS_PER_PAGE));

        if (currentPage > totalPages) {
            currentPage = totalPages;
        }
        if (currentPage < 1) {
            currentPage = 1;
        }

        // Hide all cards first
        allCards.forEach(card => card.style.display = 'none');
        emptyPageState.classList.add('hidden');

        const startIndex = (currentPage - 1) * POSTS_PER_PAGE;
        const endIndex = startIndex + POSTS_PER_PAGE;
        const pageCards = allCards.slice(startIndex, endIndex);

        if (pageCards.length > 0) {
            pageCards.forEach(card => card.style.display = '');
        } else {
            // Friendly upcoming banner for Page 3 if fewer than 19 articles
            emptyPageState.classList.remove('hidden');
        }

        // Generate numbered page buttons (1, 2, 3...)
        paginationNumbers.innerHTML = '';
        for (let p = 1; p <= totalPages; p++) {
            const btn = document.createElement('button');
            btn.className = 'pagination-num' + (p === currentPage ? ' active' : '');
            btn.textContent = p;
            btn.setAttribute('aria-label', 'Go to page ' + p);
            if (p === currentPage) {
                btn.setAttribute('aria-current', 'page');
            }
            btn.addEventListener('click', () => goToPage(p));
            paginationNumbers.appendChild(btn);
        }

        // Prev & Next button state
        prevBtn.disabled = (currentPage === 1);
        nextBtn.disabled = (currentPage === totalPages);

        // Update Summary
        if (pageCards.length > 0) {
            const fromNum = startIndex + 1;
            const toNum = startIndex + pageCards.length;
            paginationSummary.textContent = `Showing ${fromNum}–${toNum} of ${totalCards} articles`;
        } else {
            paginationSummary.textContent = `Page ${currentPage} of ${totalPages} · Upcoming articles`;
        }
    }

    function goToPage(page, shouldScroll = true) {
        currentPage = page;
        renderPagination();

        // Update URL query string
        const url = new URL(window.location);
        if (currentPage === 1) {
            url.searchParams.delete('page');
        } else {
            url.searchParams.set('page', currentPage);
        }
        window.history.pushState({ page: currentPage }, '', url);

        if (shouldScroll) {
            const section = document.getElementById('blog-section');
            if (section) {
                const headerOffset = 90;
                const elementPosition = section.getBoundingClientRect().top;
                const offsetPosition = elementPosition + window.pageYOffset - headerOffset;
                window.scrollTo({
                    top: offsetPosition,
                    behavior: 'smooth'
                });
            }
        }
    }

    function changePage(delta) {
        goToPage(currentPage + delta);
    }

    // Handle browser back/forward buttons
    window.addEventListener('popstate', () => {
        const params = new URLSearchParams(window.location.search);
        const p = parseInt(params.get('page'), 10) || 1;
        goToPage(p, false);
    });

    // Initial render
    renderPagination();
</script>

